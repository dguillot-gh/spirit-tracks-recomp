// Optional HD vector text rendering for Spirit Tracks's OBJ text boxes (NPC dialogue, signs, prompts, menu labels).
// Hooks the game's NITRO-System CharCanvas and its OBJ text objects (BKIE) to capture UTF-16 glyphs, positions, and live
// OBJ palette colors, skipping the 1x bitmap rasterization when enabled so GlPresenter renders crisp TrueType glyphs
// at the window's native resolution.
// Ported from Phantom Hourglass Recomp's ph_text (chouette-cc, phantom-hourglass-recomp PR #7); the hooks and the
// text objects' layout are Spirit Tracks's own (st_text.cpp).
#pragma once

#include <cstddef>
#include <cstdint>
#include <vector>

struct NtrCpu;
struct stbtt_fontinfo;

namespace st {

// Embedded TrueType font (Inter Bold, SIL OFL 1.1), generated by cmake/EmbedFont.cmake.
extern const unsigned char kHdFontData[];
extern const size_t kHdFontSize;

// One glyph queued for HD rendering on a DS screen (coordinates in DS pixels, 256x192).
struct HdGlyph {
    uint16_t codepoint = 0;  // UTF-16 code unit (BMP)
    float ds_x = 0.0f;       // DS screen X of the glyph slot (left bearing applied)
    float ds_y = 0.0f;       // DS screen Y of the glyph cell top
    float cell_h = 16.0f;    // NFTR cell height (DS pixels)
    float baseline = 14.0f;  // NFTR baseline offset from cell top (DS pixels)
    float slot_w = 8.0f;     // DS glyph visual width (DS pixels)
    float char_w = 8.0f;     // DS character advance width (DS pixels)
    uint32_t argb = 0xFFFFFFFFu;
    // The whole text box on the DS screen (its canvas: x0, y0, x1, y1): its letters follow a widescreen HUD move only
    // when all of it is inside the moved piece (a choice bubble beside the train lever stays whole).
    float box_x0 = 0.0f, box_y0 = 0.0f, box_x1 = 0.0f, box_y1 = 0.0f;
};

void set_hd_text_enabled(bool enabled);
bool hd_text_enabled();

// Initialized stb_truetype handle for the embedded HD font (nullptr if init failed).
const stbtt_fontinfo* hd_font_info();

// Clear tracked canvases and visible draw lists (call after loading a save state).
void hd_text_reset();

// The text recorded in the tracked canvases, for a save state: with HD text on the game never draws it into the DS's
// memory, so a state alone would bring its boxes back empty. hd_text_restore() puts back what hd_text_save() gave
// (after hd_text_reset); false if the data is not from this build's format.
std::vector<uint8_t> hd_text_save();
bool hd_text_restore(const std::vector<uint8_t>& data);

// The text boxes shown on `layer` this frame (DS pixels: x0, y0, x1, y1), HD text on or off: the minimap keeps
// out of them (main.cpp).
struct TextBox {
    float x0, y0, x1, y1;
};
void text_boxes(int layer, std::vector<TextBox>& out);

// Two-screen 3D (main.cpp): while the game draws its 3D on the top and bottom screens on alternate frames, each screen
// shows engine A's picture from the frame it was last there (engine B's copy of it is only 256 pixels wide), and so the
// text engine A drew on it then: engine B's text is left out meanwhile.
void set_dual_screen_3d(bool on);

// Copy the glyphs currently visible on `layer` (0 = top screen, 1 = bottom screen).
void hd_text_draw_list(int layer, std::vector<HdGlyph>& out);

}  // namespace st

extern "C" {
void st_text_obj_init(NtrCpu* c);
void st_text_obj_deinit(NtrCpu* c);
void st_text_clear(NtrCpu* c);
void st_text_obj_clear(NtrCpu* c);
void st_text_clear_area(NtrCpu* c);
int st_text_draw_char(NtrCpu* c);
void st_text_obj_draw(NtrCpu* c);
void st_text_oam_flush(NtrCpu* c);
}
